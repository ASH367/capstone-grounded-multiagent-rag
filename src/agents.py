"""
Milestone 1 - Three agents over the REAL CMS documents.

Each criterion has a tri-state status:
  MET      - the case record shows the criterion is satisfied
  NOT_MET  - the record shows it is violated
  UNKNOWN  - the record does not say (field is null / redacted / not reported)
Findings are assembled by code (rules + retrieved citation), not generated by an LLM;
LLM rationale generation is the Milestone 2 upgrade under the same citation contract.

`gold` is the hand-labelled chunk that states each criterion; used ONLY for the retrieval
evaluation, never for the decision.
"""
from dataclasses import dataclass, field

from retriever import PolicyRetriever
from ingest import FAQ_ID, LCD_ID

SCALE_HINTS = ("nrs", "vas", "verbal", "pdas", "odi", "oswestry", "quebec", "qbpds",
               "roland", "rdq", "bpfs", "promis")
ACCEPTED_GUIDANCE = ("fluoroscopy", "ct")
NO_SEDATION = ("none", "local", "minimal")


def num(v):
    return None if v is None else float(v)


@dataclass
class Criterion:
    name: str
    status: str            # MET | NOT_MET | UNKNOWN
    detail: str
    query: str
    gold: str
    citations: list = field(default_factory=list)
    retrieval_hit_at_1: bool = False
    retrieval_hit_at_3: bool = False

    @property
    def met(self):
        return self.status == "MET"


@dataclass
class Finding:
    agent: str
    verdict: str            # MET | NOT_MET | UNKNOWN | N/A
    criteria: list


def tri(known: bool, ok: bool) -> str:
    if not known:
        return "UNKNOWN"
    return "MET" if ok else "NOT_MET"


class BaseAgent:
    name = "base"
    DOC = None

    def __init__(self, retriever: PolicyRetriever):
        self.r = retriever

    def _cite(self, c: Criterion):
        hits = self.r.retrieve(c.query, doc_filter=self.DOC, top_k=3)
        c.retrieval_hit_at_1 = bool(hits) and hits[0]["chunk_id"] == c.gold
        c.retrieval_hit_at_3 = any(h["chunk_id"] == c.gold for h in hits)
        c.citations = [{"doc_id": h["doc_id"], "chunk_id": h["chunk_id"], "label": h["label"],
                        "score": h["score"], "snippet": h["text"][:220]} for h in hits[:1]]
        return c

    def finish(self, crits: list) -> Finding:
        crits = [self._cite(c) for c in crits]
        if any(c.status == "NOT_MET" for c in crits):
            v = "NOT_MET"
        elif any(c.status == "UNKNOWN" for c in crits):
            v = "UNKNOWN"
        else:
            v = "MET"
        return Finding(self.name, v, crits)


class EligibilityAgent(BaseAgent):
    """Is this request inside the OPD prior-authorization program? (CMS OPD PA FAQ)
    Applies only when the case carries Medicare claim data; otherwise N/A."""
    name = "EligibilityAgent"
    DOC = FAQ_ID

    def run(self, case: dict) -> Finding:
        cl = case["claim"]
        if all(v is None for v in cl.values()):
            return Finding(self.name, "N/A", [])
        tob = cl["type_of_bill"]
        c = [
            Criterion("Medicare FFS hospital OPD claim (TOB 13x)",
                      tri(tob is not None, (tob or "").startswith("13")), f"type_of_bill={tob}",
                      "hospital outpatient department services paid under OPPS type of bill 13x", "FAQ-Q58"),
            Criterion("Not an emergency department service",
                      tri(cl["emergency_dept"] is not None, cl["emergency_dept"] is False),
                      f"emergency_dept={cl['emergency_dept']}",
                      "emergency department services excluded from prior authorization ET modifier 045x", "FAQ-Q13"),
            Criterion("Prior authorization requested before service",
                      tri(cl["pa_requested_before_service"] is not None, cl["pa_requested_before_service"] is True),
                      f"pa_requested_before_service={cl['pa_requested_before_service']}",
                      "hospital OPDs must submit prior authorization request provisional affirmation condition of payment",
                      "FAQ-Q11"),
        ]
        return self.finish(c)


class MedicalNecessityAgent(BaseAgent):
    """LCD L38765 coverage criteria for the requested procedure."""
    name = "MedicalNecessityAgent"
    DOC = LCD_ID

    def run(self, case: dict) -> Finding:
        p, proc = case["clinical"], case["procedure"]
        c = []
        # Criterion 1: axial pain, moderate-to-severe, functional deficit
        pain, dis = num(p["baseline_pain_nrs"]), num(p["disability_score_pct"])
        known = p["axial_pain"] is not None and pain is not None and dis is not None
        ok = p["axial_pain"] is True and (pain or 0) >= 4 and (dis or 0) >= 20
        if p["axial_pain"] is False:
            known, ok = True, False
        c.append(Criterion("Moderate-to-severe chronic axial neck/low back pain with functional deficit",
                           tri(known, ok), f"axial={p['axial_pain']}, NRS={p['baseline_pain_nrs']}, "
                           f"{p['disability_scale']}={p['disability_score_pct']}",
                           "moderate-to-severe chronic neck or low back pain predominantly axial functional deficit pain disability scale",
                           "LCD-INDICATIONS"))
        # Criterion 2: >=3 months and failed conservative management
        dur, cons = num(p["pain_duration_months"]), p["conservative_management"]
        if cons is not None and len(cons) == 0 and dur is not None:
            st = "NOT_MET"
        elif dur is None or cons is None or len(cons) == 0:
            st = "UNKNOWN"
        else:
            st = "MET" if dur >= 3 else "NOT_MET"
        c.append(Criterion("Pain >= 3 months with documented failure of conservative management", st,
                           f"duration_months={p['pain_duration_months']}, conservative={cons}",
                           "pain present minimum of 3 months documented failure to respond to non-invasive conservative management",
                           "LCD-INDICATIONS"))
        r = p["untreated_radiculopathy"]
        c.append(Criterion("No untreated radiculopathy / neurogenic claudication",
                           tri(r is not None, r is False), f"untreated_radiculopathy={r}",
                           "absence of untreated radiculopathy or neurogenic claudication", "LCD-INDICATIONS"))
        nf = p["non_facet_pathology"]
        c.append(Criterion("No non-facet pathology explaining the pain",
                           tri(nf is not None, nf == ""), f"non_facet_pathology={nf if nf else ('none' if nf == '' else None)}",
                           "no non-facet pathology fracture tumor infection significant deformity could explain pain",
                           "LCD-INDICATIONS"))
        g = proc["guidance"]
        c.append(Criterion("Fluoroscopic or CT guidance",
                           tri(g is not None, g in ACCEPTED_GUIDANCE), f"guidance={g}",
                           "facet joint interventions without CT or fluoroscopic guidance not reasonable and necessary ultrasound",
                           "LCD-LIM1"))
        s = proc["sedation"]
        c.append(Criterion("No moderate/deep sedation, GA or MAC",
                           tri(s is not None, s in NO_SEDATION), f"sedation={s}",
                           "moderate or deep sedation general anesthesia monitored anesthesia care not reasonable and necessary facet",
                           "LCD-LIM2"))
        reg = num(proc["spinal_regions"])
        c.append(Criterion("One spinal region per session",
                           tri(reg is not None, (reg or 0) <= 1), f"spinal_regions={proc['spinal_regions']}",
                           "facet joint interventions limited to 1 spinal region per session", "LCD-LIM4"))
        cp = p["centralized_pain_dx"]
        c.append(Criterion("Not for generalized/centralized pain (e.g., fibromyalgia)",
                           tri(cp is not None, cp is False), f"centralized_pain_dx={cp}",
                           "generalized pain conditions fibromyalgia chronic centralized pain syndromes not reasonable and necessary",
                           "LCD-LIM9"))
        if proc["type"] == "rfa":
            dx = proc["prior_diagnostic_mbb_relief_pct"]
            if dx is None or len(dx) == 0:
                st = "UNKNOWN"
            else:
                st = "MET" if len(dx) >= 2 and all(x >= 80 for x in dx) else "NOT_MET"
            c.append(Criterion("RFA: 2 prior diagnostic MBBs each >= 80% relief", st,
                               f"prior_diagnostic_mbb_relief_pct={dx}",
                               "initial thermal radiofrequency destruction at least 2 diagnostic MBBs each consistent minimum 80% sustained relief",
                               "LCD-C-DENERVATION"))
        return self.finish(c)


class DocumentationAgent(BaseAgent):
    """Is the required evidence present in the submitted record?"""
    name = "DocumentationAgent"
    DOC = LCD_ID

    def run(self, case: dict) -> Finding:
        d = case["documentation"]
        ps, ds = d["pain_scale_used"], d["disability_scale_used"]
        c = []
        bp = d["baseline_pain_documented"]
        c.append(Criterion("Baseline pain assessment on an accepted scale",
                           tri(bp is not None, bool(bp) and any(h in (ps or "").lower() for h in SCALE_HINTS)),
                           f"documented={bp}, scale={ps}",
                           "pain assessment must be performed and documented at baseline using the same pain scale",
                           "LCD-INDICATIONS"))
        bd = d["baseline_disability_documented"]
        c.append(Criterion("Baseline disability scale on an accepted instrument",
                           tri(bd is not None, bool(bd) and any(h in (ds or "").lower() for h in SCALE_HINTS)),
                           f"documented={bd}, scale={ds}",
                           "disability scale must be obtained at baseline functional assessment accepted scales Oswestry",
                           "LCD-SCALES"))
        cr = d["conservative_records_attached"]
        c.append(Criterion("Conservative-management records in submission",
                           tri(cr is not None, cr is True), f"conservative_records_attached={cr}",
                           "documented failure to respond to non-invasive conservative management",
                           "LCD-INDICATIONS"))
        return self.finish(c)
